# Suite generation.
def load_columns(path: Path = gold_checks.SILVER_COLUMNS) -> dict[str, list[tuple[str, str]]]:
    """The kept silver models with their ordered columns and types."""
    return {name: [(column, kind) for column, kind in entry["columns"]] for name, entry in sorted(json.loads(path.read_text())["models"].items())}


def has_floor(model: str) -> bool:
    """Every kept model must hold a row except the hold models and the marker: a real build may hold nothing for a source [853]."""
    return model != MARKER and not model.endswith("_holds")


def typeof_query(columns: list[tuple[str, str]]) -> str:
    """The original type check of the moved adjacency contract: the first row's typeof per column."""
    tests = " OR ".join(gold_checks.build("typeof($name) <> $kind", name=name, kind=gold_checks.literal(kind)) for name, kind in columns)
    return gold_checks.build("SELECT * FROM (SELECT * FROM {batch} LIMIT 1) WHERE $tests", tests=tests)


def model_expectations(model: str, columns: list[tuple[str, str]]) -> list[dict[str, Any]]:
    """The atomic contract of one kept model: columns, rows and types, all structural."""
    names = [name for name, _ in columns]
    floor = gold_checks.expectation(model, "has_rows", "ExpectTableRowCountToBeBetween", {"min_value": 1})
    if model == MARKER:
        # The marker gains columns later, so only the columns the validator reads are required, and exactly one row.
        one = gold_checks.expectation(model, "has_rows", "ExpectTableRowCountToBeBetween", {"min_value": 1, "max_value": 1})
        return [one, gold_checks.unexpected(model, "types", gold_checks.types_query(model, columns))]
    if model == ORIGINAL_FORM:
        ordered = gold_checks.expectation(model, "columns", "ExpectTableColumnsToMatchOrderedList", {"column_list": names})
        return [ordered, floor, gold_checks.unexpected(model, "types", typeof_query(columns))]
    # A set, because silver_columns.json orders two models' columns differently from their build (the gold contract also compares sets).
    out = [gold_checks.expectation(model, "columns", "ExpectTableColumnsToMatchSet", {"column_set": names})]
    out += [floor] if has_floor(model) else []
    return out + [gold_checks.unexpected(model, "types", gold_checks.types_query(model, columns))]


def band_models(document: dict[str, Any]) -> list[str]:
    """The models that have a row-count band (approved or proposed) in a baselines document."""
    names = {**document.get("values", {}), **document.get("proposed_values", {})}
    pattern = re.compile(r"silver\.rows\.(.+)\.min")
    return sorted(match[1] for name in names if (match := pattern.fullmatch(name)) and f"silver.rows.{match[1]}.max" in names)


def build_suites(models: dict[str, list[tuple[str, str]]], baselines: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """The silver suites by file stem: the contract of every kept model, the moved spatial checks and the row-count bands."""
    contract = [item for model, columns in models.items() for item in model_expectations(model, columns)]
    spatial = [gold_checks.unexpected(ORIGINAL_FORM, tag.split(".", 1)[1], sql) | {"id": tag} for tag, sql in SPATIAL.items()]
    suites = {
        "silver_contract": gold_checks.suite("silver_contract", "Every kept silver model has its column set, its types and rows (failure mode 853)", contract),
        "silver_spatial": gold_checks.suite("silver_spatial", "County adjacency edges for the spatial work (failure mode 854)", spatial),
    }
    bands = []
    for model in band_models(baselines):
        kwargs = {"min_value": f"<<silver.rows.{model}.min>>", "max_value": f"<<silver.rows.{model}.max>>"}
        bands.append(gold_checks.expectation(model, "row_count", "ExpectTableRowCountToBeBetween", kwargs) | {"severity": "distribution"})
    if bands:
        suites["silver_row_counts"] = gold_checks.suite(
            "silver_row_counts", "Row counts of the kept models stay inside their bands (proposed until the owner approves)", bands
        )
    return suites


def write_suites(out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for stem, document in build_suites(load_columns(), json.loads(BASELINES.read_text())).items():
        path = out / f"{stem}.json"
        path.write_text(gold_checks.render(document))
        written.append(path)
    return written


# Static checks.
def folder_expectations(folder: Path) -> list[dict[str, Any]]:
    return [item for path in sorted(folder.glob("*.json")) for item in json.loads(path.read_text())["expectations"]]


def saved_ids() -> set[str]:
    """The ids of the checks saved with the feature files: everything in the saved suites except the six moved checks."""
    return {item["id"] for item in folder_expectations(SAVED_SUITES)} - set(MOVED) if SAVED_SUITES.is_dir() else set()


def band_problems(label: str, document: dict[str, Any]) -> list[str]:
    values, proposed = document.get("values", {}), document.get("proposed_values", {})
    problems = [f"{label}: {name} is both approved and proposed" for name in sorted(set(values) & set(proposed))]
    if proposed and document.get("proposed_approved") is not False:
        problems.append(f"{label}: proposed values must say proposed_approved is false until the owner approves them")
    return problems


def static_problems(silver_dir: Path, gold_dir: Path, baselines: Path = BASELINES, fixture: Path = FIXTURE_BASELINES) -> dict[str, list[str]]:
    """Every difference between the committed suites and what their sources require, by category [853] [854] [855] [856]."""
    models = load_columns()
    docs = {"baselines.json": json.loads(baselines.read_text()), "fixture_baselines.json": json.loads(fixture.read_text())}
    problems: dict[str, list[str]] = {"contract": [], "moved": [], "saved": [], "archived": [], "baselines": [], "gold": [], "ids": []}
    wanted = build_suites(models, docs["baselines.json"])
    found = {path.stem for path in silver_dir.glob("*.json")} if silver_dir.is_dir() else set()
    problems["contract"] += [f"suite {stem} is missing" for stem in sorted(set(wanted) - found)]
    problems["contract"] += [f"suite {stem} is not generated" for stem in sorted(found - set(wanted))]
    for stem, document in wanted.items():
        path = silver_dir / f"{stem}.json"
        if path.is_file() and path.read_text() != gold_checks.render(document):
            problems["contract"].append(f"suite {stem} differs from what its sources generate")
    items = folder_expectations(silver_dir) if silver_dir.is_dir() else []
    ids = [item["id"] for item in items]
    problems["moved"] += [f"moved check {name} is missing" for name in MOVED if name not in ids]
    problems["saved"] += [f"{name} is a saved check and must not run in silver" for name in sorted(set(ids) & saved_ids())]
    reference = {item["id"]: item for item in folder_expectations(SAVED_SUITES)} if SAVED_SUITES.is_dir() else {}
    problems["moved"] += [
        f"moved check {item['id']} differs from its saved original" for item in items if item["id"] in MOVED and reference.get(item["id"], item) != item
    ]
    known = {**docs["baselines.json"].get("values", {}), **docs["baselines.json"].get("proposed_values", {})}
    for item in items:
        text = json.dumps([item["table"], item["kwargs"]])
        problems["archived"] += [f"{item['id']} names {name}, which is not a kept silver model" for name in sorted(set(MODEL_NAME.findall(text)) - set(models))]
        if item["type"] not in ALLOWED_TYPES:
            problems["contract"].append(f"{item['id']} uses the unknown type {item['type']}")
        for name in PLACEHOLDER.findall(text):
            if name not in known:
                problems["baselines"].append(f"{item['id']} uses {name}, which baselines.json lacks")
            if name in docs["baselines.json"].get("proposed_values", {}) and item["severity"] != "distribution":
                problems["baselines"].append(f"{item['id']} is structural and uses the proposed band {name}")
    for label, document in docs.items():
        problems["baselines"] += band_problems(label, document)
    if band_models(docs["baselines.json"]) != band_models(docs["fixture_baselines.json"]):
        problems["baselines"].append("baselines.json and fixture_baselines.json band different models")
    problems["gold"] += gold_checks.suites_problems(gold_checks.load_contract(), gold_dir)
    gold_ids = [item["id"] for item in folder_expectations(gold_dir)] if gold_dir.is_dir() else []
    problems["ids"] += [f"expectation id {name} repeats" for name in sorted({name for name in ids + gold_ids if (ids + gold_ids).count(name) > 1})]
    return problems


def flat(problems: dict[str, list[str]]) -> list[str]:
    return [f"{category}: {problem}" for category, items in problems.items() for problem in items]


def edit_json(path: Path, change: Callable[[dict[str, Any]], None]) -> None:
    document = json.loads(path.read_text())
    change(document)
    path.write_text(gold_checks.render(document))


def drop_id(name: str) -> Callable[[dict[str, Any]], None]:
    def change(document: dict[str, Any]) -> None:
        document["expectations"] = [item for item in document["expectations"] if item["id"] != name]

    return change


def add_item(item: dict[str, Any]) -> Callable[[dict[str, Any]], None]:
    return lambda document: document["expectations"].append(item)


