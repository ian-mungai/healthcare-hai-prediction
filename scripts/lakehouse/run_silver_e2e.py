def tiny_suite(work: Path, name: str, items: list[dict[str, Any]]) -> Path:
    folder = work / name
    folder.mkdir()
    (folder / "suite.json").write_text(gold_checks.render(gold_checks.suite(name, name, items)))
    return folder


def stop_cases(work: Path) -> list[tuple[str, str, list[Path], Path | None, str]]:
    """(name, SQL on the build, suite folders, baselines file, text the stop must contain)."""
    table = "int_cmi_file_layouts"
    band = {"min_value": f"<<silver.rows.{table}.min>>"}
    structural = tiny_suite(work, "structural", [gold_checks.expectation(table, "rows", "ExpectTableRowCountToBeBetween", band)])
    unknown = tiny_suite(
        work, "unknown", [gold_checks.expectation(table, "rows", "ExpectTableRowCountToBeBetween", {"min_value": "<<silver.rows.nowhere.min>>"})]
    )
    repeated = tiny_suite(work, "repeated", [gold_checks.expectation(table, "has_rows", "ExpectTableRowCountToBeBetween", {"min_value": 1})])
    own = tiny_suite(work, "own", [gold_checks.expectation(table, "has_rows", "ExpectTableRowCountToBeBetween", {"min_value": 1})])
    names = (f"silver.rows.{table}.min", f"silver.rows.{table}.max")

    def variant(kind: str, proposed: dict[str, Any], keep: tuple[str, ...] = ()) -> Path:
        # The committed bands are owner-approved, so each proposal exists only here: the band leaves values unless kept, and returns as proposed.
        document = json.loads(FIXTURE_BASELINES.read_text())
        for name in set(names) - set(keep):
            document["values"].pop(name)
        document["proposed_values"] = proposed
        path = work / f"{kind}_baselines.json"
        path.write_text(json.dumps(document, indent=2) + "\n")
        return path

    current = json.loads(FIXTURE_BASELINES.read_text())["values"]
    proposed_path = variant("proposed", {name: current[name] for name in names})
    both_path = variant("both", {name: current[name] for name in names}, keep=(names[0],))
    inverted_path = variant("inverted", {names[0]: 99, names[1]: 1})
    missing_path = variant("missing", {names[1]: current[names[1]]})
    return [
        ("no_marker", mutation("DROP TABLE $table;", table=MARKER), [SILVER_SUITES], None, f"no {MARKER}"),
        ("other_duckdb_version", mutation("UPDATE $table SET duckdb_version = 'v0.0.0';", table=MARKER), [SILVER_SUITES], None, "written by DuckDB v0.0.0"),
        ("proposed_band_in_structural", "", [structural], proposed_path, "is structural and uses the proposed baseline"),
        ("unknown_placeholder", "", [unknown], None, "baseline silver.rows.nowhere.min is not in baselines.json"),
        ("name_both_approved_and_proposed", "", [SILVER_SUITES], both_path, "both approved and proposed"),
        ("band_minimum_above_maximum", "", [SILVER_SUITES], inverted_path, "invalid arguments"),
        ("band_name_missing", "", [SILVER_SUITES], missing_path, f"silver.rows.{table}.min is not in baselines.json"),
        ("id_repeated_across_folders", "", [repeated, own], None, "expectation ids repeat across suites"),
    ]


def apply_sql(path: Path, sql: str) -> None:
    """Run the case's change with the DuckDB CLI (the same 1.5.6 engine as the images)."""
    if sql:
        result = run_command("duckdb", [str(path), "-c", sql], cwd=REPO_ROOT, timeout=300)
        if result.returncode:
            raise RuntimeError(f"case SQL failed on {path.parent.name}: {result.stderr.strip().splitlines()[-1:]}")


def make_copy(base: Path, scratch: Path, name: str, sql: str) -> Path:
    folder = scratch / name
    folder.mkdir()
    shutil.copyfile(base, folder / "build.duckdb")
    apply_sql(folder / "build.duckdb", sql)
    return folder


def host_duckdb_matches_image() -> bool:
    result = run_command("duckdb", ["--version"], timeout=60)
    return result.returncode == 0 and f"v{QUALITY_IMAGE.rsplit('duckdb', 1)[1]}" in result.stdout


def expectation_count() -> int:
    return len(folder_expectations(SILVER_SUITES)) + len(folder_expectations(GOLD_SUITES))


def checks_on_good(run: Run, record: dict[str, Any], build: dict[str, Any]) -> None:
    """The good case: both suite sets ran in full and passed, and each moved check equals its result on the saved reference [855]."""
    seen = {item["id"]: item for item in record.get("expectations", [])}
    run.checks["good.suites_listed"] = sorted(record.get("suites", {})) == suite_names()
    run.checks["good.no_missing_tables"] = record.get("missing_tables") == []
    run.checks["good.moved_checks_equal_saved_reference"] = all(
        name in seen and seen[name]["level"] == level and (value is None or seen[name].get("observed_value") == value)
        for name, (level, value) in SAVED_REFERENCE.items()
    )
    edges = record.get("tables", {}).get(ORIGINAL_FORM, {})
    build["adjacency_edges"] = edges


def suite_names() -> list[str]:
    return sorted(json.loads(path.read_text())["name"] for folder in (SILVER_SUITES, GOLD_SUITES) for path in folder.glob("*.json"))


def kit_stem(run_id: str) -> str:
    """The kit case stem of one run: the kit deletes every earlier folder of a stem, so a run ID in the stem keeps each run's build [857]."""
    return f"silver_fixture_{run_id}"


def evidence_of(case_folder: Path) -> dict[str, Any]:
    """Name a build's kit case folder, its manifest and its run results with their hashes, so a later run can prove they are still there [857]."""
    record: dict[str, Any] = {"case": str(case_folder.relative_to(REPO_ROOT))}
    for key, relative in (("manifest", "target/manifest.json"), ("run_results", "target/run_results.json"), ("build", "staging.duckdb")):
        path = case_folder / relative
        record[key] = {
            "path": str(path.relative_to(REPO_ROOT)),
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() and key != "build" else None,
        }
    results = case_folder / "target/run_results.json"
    record["invocation_id"] = json.loads(results.read_text()).get("metadata", {}).get("invocation_id") if results.is_file() else None
    return record


def evidence_problems(record: dict[str, Any]) -> list[str]:
    """Each recorded evidence file that is missing or whose hash changed [857]."""
    problems = []
    for key in ("manifest", "run_results", "build"):
        item = record.get(key, {})
        path = REPO_ROOT / str(item.get("path", ""))
        if not path.is_file():
            problems.append(f"{key} is missing: {item.get('path')}")
        elif item.get("sha256") and hashlib.sha256(path.read_bytes()).hexdigest() != item["sha256"]:
            problems.append(f"{key} changed: {item.get('path')}")
    return problems


def earlier_evidence(reports: Path = REPORTS) -> dict[str, list[str]]:
    """The problems of every earlier full run that recorded its build evidence, by run ID; an earlier report without a record is not judged [857]."""
    found: dict[str, list[str]] = {}
    for path in sorted(reports.glob("fixture_*/report.json")):
        try:
            report = json.loads(path.read_text())
        except (OSError, ValueError):
            continue
        record = report.get("fixture", {}).get("build", {}).get("evidence") if report.get("mode") == "full" else None
        if record:
            found[str(report.get("run_id", path.parent.name))] = evidence_problems(record)
    return found


def evidence_cases(run: Run) -> dict[str, Any]:
    """Repeatable cases for the evidence rules: a stem per run that no other run's kit cleanup matches, and a missing or changed file is reported [857]."""
    first, second = "20261012T000000Z-aaaaaaaa", "20261012T000001Z-bbbbbbbb"
    stems_differ = kit_stem(first) != kit_stem(second)
    cross_match = fnmatch.fnmatchcase(f"{kit_stem(second)}--0123abcd", f"{kit_stem(first)}--*")
    self_match = fnmatch.fnmatchcase(f"{kit_stem(first)}--0123abcd", f"{kit_stem(first)}--*")
    old_stem_match = fnmatch.fnmatchcase("silver_fixture--8718f7d6", f"{kit_stem(first)}--*")
    run.checks["evidence.stem_of_one_run_is_not_cleaned_by_another"] = stems_differ and self_match and not cross_match and not old_stem_match
    with tempfile.TemporaryDirectory(prefix="silver_evidence_") as temp:
        reports = Path(temp) / "reports"
        folder = REPO_ROOT / "data/e2e/silver_quality/evidence_probe_does_not_exist"
        probe = {key: {"path": f"{folder.relative_to(REPO_ROOT)}/{key}", "sha256": None} for key in ("manifest", "run_results", "build")}
        (reports / "fixture_probe").mkdir(parents=True)
        (reports / "fixture_probe/report.json").write_text(json.dumps({"mode": "full", "run_id": "probe", "fixture": {"build": {"evidence": probe}}}))
        (reports / "fixture_old").mkdir()
        (reports / "fixture_old/report.json").write_text(json.dumps({"mode": "full", "run_id": "old", "fixture": {"build": {}}}))
        found = earlier_evidence(reports)
    run.checks["evidence.missing_evidence_of_an_earlier_run_is_reported"] = len(found.get("probe", [])) == 3 and "old" not in found
    return {"stems_differ": stems_differ, "missing_reported": found.get("probe")}


def fixture_stage(run: Run, args: argparse.Namespace) -> None:
    """Take one launcher allocation (or reuse the caller's ``HAI_ALLOCATION``), then build and check; the allocation this run took is released at the end,
    which the launcher allows only after every attempt of it has ended and its container is gone [857]."""
    stage: dict[str, Any] = {"cases": {}}
    run.report["fixture"] = stage
    run.enter("fixture:admission")
    client = launcher.load_client(package_fixture.TEST_REGISTRY)
    inherited = os.environ.get("HAI_ALLOCATION")
    allocation = inherited or client.allocate()
    run.session = package_fixture.Session(client, allocation)
    stage["allocation"] = {"id": allocation, "inherited": bool(inherited)}
    package_fixture.ACTIVE.append(run.session)
    try:
        fixture_cases(run, args, run.session, stage)
    finally:
        package_fixture.ACTIVE.remove(run.session)
        if not inherited:
            try:
                run.allocation_release = client.release_allocation(allocation)
            except (launcher.ClientError, OSError) as error:
                run.allocation_release = launcher.ReleaseOutcome.UNRESOLVED
                stage["allocation"]["release_error"] = str(error)
            stage["allocation"]["release"] = run.allocation_release.value


def fixture_cases(run: Run, args: argparse.Namespace, session: package_fixture.Session, stage: dict[str, Any]) -> None:
    """Build silver and gold on the fixture bronze, then run the good case, every mutation and every stop [857]."""
    models = load_columns()
    started = time.monotonic()
    scratch = package_fixture.OUT / f"silver_cases--{run.run_id}"
    scratch.mkdir(parents=True)
    run.scratch = scratch
    run.enter("fixture:build")
    if args.inject == "build-fail":
        raise RuntimeError("injected fault in the fixture build")
    if args.build_file:
        base = Path(args.build_file).resolve()
        run.checks["fixture_build_passes"] = base.is_file()
    else:
        case = package_fixture.make_case(kit_stem(run.run_id), session, [])
        code, tail, by_id = package_fixture.dbt(case, ["build"], session)
        statuses = run_gold_e2e.statuses_by_name(by_id)
        manifest = json.loads((case.folder / "target/manifest.json").read_text()) if (case.folder / "target/manifest.json").is_file() else {}
        problems = run_gold_e2e.not_passing(statuses) + (run_gold_e2e.gold_node_problems(manifest, statuses, True) if manifest else ["no manifest"])
        run.checks["fixture_build_passes"] = code == 0 and bool(statuses) and not problems
        stage["build"] = {
            "nodes": len(statuses),
            "not_passing": problems[:30],
            "evidence": evidence_of(case.folder),
        }
        if not statuses:
            stage["build"]["tail"] = tail[-400:]
            return
        base = case.folder / "staging.duckdb"
        stage["build"]["dbt_tree_sha256"] = run_gold_e2e.staging.dbt_tree_sha256()
        manifest_path = case.folder / "target/manifest.json"
        repeated = [name for folder in (SILVER_SUITES, GOLD_SUITES) for name in silver.repeated_dbt_tests(folder, manifest_path)]
        run.checks["no_expectation_repeats_a_dbt_test"] = not repeated
        stage["repeated_dbt_tests"] = repeated
        run.checks["evidence.this_build_is_present"] = not evidence_problems(stage["build"]["evidence"])
        earlier = earlier_evidence()
        stage["earlier_builds"] = {key: value for key, value in earlier.items()}
        run.checks["evidence.earlier_full_runs_are_still_present"] = not any(earlier.values())
        stage["evidence_cases"] = evidence_cases(run)
    stage["build_file"] = str(base.relative_to(REPO_ROOT)) if base.is_relative_to(REPO_ROOT) else str(base)
    run.checks["host_duckdb_matches_image"] = host_duckdb_matches_image()
    expected = expectation_count()
    stage["expectations_in_files"] = expected
    run.enter("fixture:cases")
    work = scratch / "work"
    work.mkdir()
    both = [SILVER_SUITES, GOLD_SUITES]
    for case_item in cases(models):
        folder = make_copy(base, scratch, case_item.name, case_item.sql)
        baselines = FIXTURE_BASELINES if case_item.baselines == "fixture" else baseline_variant(case_item.baselines, work)
        faulted = case_item.name == "good" and run.fault == "quality-timeout"
        code, record = quality_container(run, folder, "build.duckdb", both, baselines, SHORT_LAUNCH if faulted else None)
        ok, detail = judge(case_item, code, record, expected)
        run.checks[f"case.{case_item.name}"] = ok
        stage["cases"][case_item.name] = detail
        if case_item.name == "good":
            checks_on_good(run, record, stage)
            (work / "good_record.json").write_text(json.dumps(record, indent=2) + "\n")
            stage["good_counts"] = record.get("counts")
            stage["row_counts"] = {table: item["rows"] for table, item in record.get("tables", {}).items() if table in models}
        shutil.rmtree(folder / "out", ignore_errors=True)
    run.enter("fixture:stops")
    for name, sql, suites, stop_baselines, text in stop_cases(work):
        folder = make_copy(base, scratch, f"stop_{name}", sql)
        code, record = quality_container(run, folder, "build.duckdb", suites, stop_baselines or FIXTURE_BASELINES)
        run.checks[f"stop.{name}"] = code == 2 and text in json.dumps(record)
        stage["cases"][f"stop_{name}"] = {"exit_code": code, "error": record.get("error")}
    run.checks["quality_runs_are_launcher_attempts"] = bool(run.attempts) and all("attempt" in item and "reason" in item for item in run.attempts)
    stage["seconds"] = round(time.monotonic() - started, 1)
    if (work / "good_record.json").is_file():
        keep = REPORTS / f"fixture_{run.run_id}"
        keep.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(work / "good_record.json", keep / "good_record.json")


def static_stage(run: Run) -> None:
    """The static checks of the committed suites and a repeatable negative case for each rule [854] [855] [856]."""
    run.enter("static")
    problems = static_problems(SILVER_SUITES, GOLD_SUITES)
    run.report["static"] = {"problems": {key: value[:10] for key, value in problems.items() if value}}
    for category, items in problems.items():
        run.checks[f"static.{category}_clean"] = not items
    for name, (category, edit) in static_mutations().items():
        with tempfile.TemporaryDirectory(prefix="silver_static_") as temp:
            silver_dir, gold_dir = Path(temp) / "silver", Path(temp) / "gold"
            shutil.copytree(SILVER_SUITES, silver_dir)
            shutil.copytree(GOLD_SUITES, gold_dir)
            edit(silver_dir, gold_dir)
            found = static_problems(silver_dir, gold_dir)
            run.checks[f"static_mutation.{name}"] = bool(found[category])
    run.report["static"]["mutations"] = sorted(static_mutations())


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--write-suites", action="store_true", help="write the silver suites generated from silver_columns.json, the moved checks and baselines.json"
    )
    parser.add_argument("--check-suites", action="store_true", help="static checks only, no Docker; fails when the suites differ from their sources")
    parser.add_argument("--build-file", type=Path, help="run the fixture stage on a finished build instead of building: an iteration run, not commit evidence")
    parser.add_argument("--inject", choices=FAULTS, help="raise a fault in the fixture stage to show that the report is still written")
    parser.add_argument("--test-registry", help="a test registry folder (for runs before the real registry serves the launcher, and tests of this runner)")
    args = parser.parse_args()
    package_fixture.TEST_REGISTRY = args.test_registry
    if args.write_suites:
        written = write_suites(SILVER_SUITES)
        sys.stdout.write(f"wrote {len(written)} silver suites to {SILVER_SUITES.relative_to(REPO_ROOT)}\n")
        return 0
    if args.check_suites:
        found = flat(static_problems(SILVER_SUITES, GOLD_SUITES))
        for problem in found:
            sys.stderr.write(f"{problem}\n")
        sys.stdout.write(f"silver suites: {len(found)} differences\n")
        return 1 if found else 0
    run = Run("iteration" if args.build_file else "full", fault=args.inject)
    run.report |= {
        "started_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "image": package_fixture.IMAGE,
        "quality_image": QUALITY_IMAGE,
        "inject": args.inject,
        "registry": "test" if args.test_registry else "real",
    }
    started = time.monotonic()
    code = 1
    try:
        static_stage(run)
        fixture_stage(run, args)
    except KeyboardInterrupt:
        run.stop("KeyboardInterrupt", "the run was interrupted")
        code = 130
    except SystemExit as stop:
        run.stop("SystemExit", str(stop.code))
        code = 2
    except Exception as error:
        run.stop(type(error).__name__, str(error))
    finally:
        path = run.finalize(started)
    for name, ok in sorted(run.checks.items()):
        sys.stdout.write(f"{'PASS' if ok else 'FAIL'} {name}\n")
    where = f"report {path.relative_to(REPO_ROOT)}" if path else "no report written"
    note = "; iteration run: not commit evidence" if args.build_file else ""
    sys.stdout.write(
        f"silver quality e2e ({run.report['mode']}): {run.report['passed']} of {run.report['total']} passed; phase {run.phase}; "
        f"run {run.run_id}; {where}{note}\n"
    )
    ok = run.report["passed"] == run.report["total"] and run.report["total"] > 0 and path is not None
    return 0 if ok else code


if __name__ == "__main__":
    sys.exit(main())
