"""E2E for the silver and gold Great Expectations checks on the atomic silver models (failure modes 853 to 857).

Run from the repository root with Docker running:

    .venv/bin/python -m scripts.lakehouse.run_silver_e2e                      # static checks, then the fixture stage (full)
    .venv/bin/python -m scripts.lakehouse.run_silver_e2e --check-suites       # static checks only: no Docker (CI)
    .venv/bin/python -m scripts.lakehouse.run_silver_e2e --write-suites       # regenerate the silver suites from their sources
    .venv/bin/python -m scripts.lakehouse.run_silver_e2e --build-file FILE    # fixture stage on a finished build: an iteration run, not commit evidence
    .venv/bin/python -m scripts.lakehouse.run_silver_e2e --test-registry DIR  # the same on a test registry's launcher (before the real one serves)

The silver suites are generated from ``data_contracts/lakehouse/silver_columns.json`` (the kept models), the six moved adjacency checks and the
bands of ``baselines.json``; the gold suites are generated by ``gold_checks.py`` and are read-only here. The fixture stage is a launcher client
(D1): under one launcher allocation it builds silver and gold on the synthetic bronze with the package fixture kit, runs ``silver_quality`` as a
``quality_validate`` attempt over both suite folders, then runs each mutation on a copy of the build and requires that exactly the named
expectations fail or warn. The launcher owns every container: an attempt ends only after its container is removed and proved absent, and the
allocation cannot be released while an attempt of it is open, so admission never outlives a running validation (D1 section 4 items 1a and 7;
amendments A50 item 2 and A51 item 3, converted at the C3a integration). It never starts the catalog, reads bronze or touches a secret.

The report goes to ``data/e2e/silver_quality/fixture_<UTC>/report.json`` with the run ID, mode, phase, every check by name and counts only. An
interrupt, an exit or an error in any phase still writes the report with the verdict so far, and the run fails.
"""

