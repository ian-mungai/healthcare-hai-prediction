def baseline_variant(kind: str, work: Path) -> Path:
    """A copy of the fixture baselines with the band of int_cmi_file_layouts moved to 1, below its count, in the way the case name says [856]."""
    document = json.loads(FIXTURE_BASELINES.read_text())
    keys = ("silver.rows.int_cmi_file_layouts.min", "silver.rows.int_cmi_file_layouts.max")
    if kind == "proposed_shifted":
        # The committed bands are approved, so the proposal exists only here: the band leaves values and returns as a proposal.
        for key in keys:
            document["values"].pop(key)
        document["proposed_values"] = dict.fromkeys(keys, 1)
        document["proposed_approved"] = False
    else:
        document["values"] |= dict.fromkeys(keys, 1)
        document["approved"] = kind == "approved_shifted"
    path = work / f"{kind}_baselines.json"
    path.write_text(json.dumps(document, indent=2) + "\n")
    return path


def levels(record: dict[str, Any]) -> dict[str, str]:
    return {item["id"]: item["level"] for item in record.get("expectations", [])}


def judge(case: Case, code: int, record: dict[str, Any], expected_count: int) -> tuple[bool, dict[str, Any]]:
    """A case passes when exactly its named expectations fail or warn, every expectation ran and the record holds no sentinel [857]."""
    seen = levels(record)
    failed = {key for key, level in seen.items() if level == "fail"}
    warned = {key for key, level in seen.items() if level == "warn"}
    expected_code = case.code if case.code is not None else (1 if case.fail else 0)
    detail = {
        "exit_code": code,
        "counts": record.get("counts"),
        "error": record.get("error"),
        "unexpected_fail": sorted(failed - case.fail)[:10],
        "missing_fail": sorted(case.fail - failed)[:10],
        "unexpected_warn": sorted(warned - case.warn)[:10],
        "missing_warn": sorted(case.warn - warned)[:10],
        "expectations": len(seen),
    }
    ok = (
        bool(seen)
        and failed == case.fail
        and warned == case.warn
        and code == expected_code
        and len(seen) == expected_count
        and SENTINEL not in json.dumps(record)
    )
    return ok, detail


