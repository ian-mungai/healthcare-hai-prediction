def render_definitions(schema: dict[str, Any]) -> str:
    """The Feast repository file: the view data from the schema, the fixed code around it."""
    predictor: dict[str, list[tuple[str, str]]] = {}
    for name, table in schema["tables"].items():
        if table["role"] == "predictor":
            predictor[name] = [(column["name"], column["feast_type"]) for column in table["columns"] if column["role"] == "predictor"]
    labels = schema["tables"][LABEL_TABLE]
    by_name = {column["name"]: column["feast_type"] for column in labels["columns"] if column["role"] == "label"}
    out = [DEFINITIONS_HEAD.format(generated=GENERATED_LINE, event_time=EVENT_TIME) + "PREDICTOR_VIEWS: dict[str, tuple[tuple[str, str], ...]] = {"]
    for name, fields in predictor.items():
        out.append(f'    "{name}": (')
        out += [f'        ("{column}", "{dtype}"),' for column, dtype in fields]
        out.append("    ),")
    out += ["}", "LABEL_VIEWS: dict[str, tuple[str, tuple[tuple[str, str], ...]]] = {"]
    for view, names in labels["label_views"].items():
        out += [f'    "{view}": (', f'        "{LABEL_TABLE}",', "        (", *[f'            ("{column}", "{by_name[column]}"),' for column in names]]
        out += ["        ),", "    ),"]
    out.append("}")
    tail = DEFINITIONS_TAIL.format(entity=ENTITY, join_key=SPINE_KEY)
    registered = [f'{name} = view("{name}", True)' for name in predictor] + [f'{view} = view("{view}", False)' for view in labels["label_views"]]
    return "\n".join(out) + "\n" + tail + "\n".join(registered) + "\n"


def generated_files(root: Path = REPO_ROOT) -> dict[str, str]:
    """Every generated file by repository path, from one computation."""
    schema = build_schema(root)
    files = {SCHEMA: schema_text(schema), MATRIX_YAML: render_yaml(schema), DEFINITIONS: render_definitions(schema)}
    for name, table in schema["tables"].items():
        files[f"{MATRIX_FOLDER}/{name}.sql"] = render_model(name, table)
    return files


def schema_sha256(root: Path = REPO_ROOT) -> str:
    """SHA-256 of the committed schema file's bytes."""
    return hashlib.sha256((root / SCHEMA).read_bytes()).hexdigest()


def load_schema(root: Path = REPO_ROOT) -> dict[str, Any]:
    """The committed schema document."""
    document: dict[str, Any] = read_json(root / SCHEMA)
    return document


def model_files(root: Path) -> set[str]:
    """The ``feature_matrix_*`` and ``label_matrix_*`` model names that exist as SQL files in the matrix folder."""
    folder = root / MATRIX_FOLDER
    return {path.stem for path in folder.glob("*.sql") if MODEL_PATTERN.fullmatch(path.stem)} if folder.is_dir() else set()


def check(root: Path = REPO_ROOT) -> list[str]:
    """Problems between the committed files and the generator's output."""
    try:
        expected = generated_files(root)
    except SchemaError as error:
        return [f"{SCHEMA}:1: the schema cannot be generated: {error}"]
    problems = []
    for path, text in expected.items():
        target = root / path
        if not target.is_file():
            problems.append(f"{path}:1: the generated file is missing; run python -m scripts.features.feature_schema generate")
        elif target.read_text() != text:
            problems.append(
                f"{path}:1: differs from the generator's output; run python -m scripts.features.feature_schema generate (do not edit generated files)"
            )
    named = {Path(path).stem for path in expected if path.endswith(".sql")}
    for model in sorted(model_files(root) - named):
        problems.append(f"{MATRIX_FOLDER}/{model}.sql:1: model {model} has no entry in {SCHEMA}")
    return problems


def servable_in_definitions(text: str) -> list[str]:
    """The ``<view>:<feature>`` references that a definitions file registers as predictors, read from its text (Feast is not imported)."""
    for node in ast.parse(text).body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.target.id == "PREDICTOR_VIEWS" and node.value is not None:
            views = ast.literal_eval(node.value)
            return [f"{view}:{column}" for view, fields in views.items() for column, _ in fields]
    return []


def generate(root: Path = REPO_ROOT) -> list[str]:
    """Write every generated file; computes all before writing, so a schema error writes nothing. Returns the paths written."""
    files = generated_files(root)
    folder = root / MATRIX_FOLDER
    folder.mkdir(parents=True, exist_ok=True)
    for stale in sorted(model_files(root) - {Path(path).stem for path in files if path.endswith(".sql")}):
        (folder / f"{stale}.sql").unlink()
    for path, text in files.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.is_file() or target.read_text() != text:
            target.write_text(text)
    return sorted(files)


def main(argv: Sequence[str] | None = None) -> int:
    """Generate the files or check them."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("action", choices=("generate", "check"))
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    args = parser.parse_args(list(sys.argv[1:] if argv is None else argv))
    if args.action == "generate":
        try:
            written = generate(args.root)
        except SchemaError as error:
            sys.stderr.write(f"feature schema: {error}\n")
            return 1
        sys.stdout.write(f"feature schema: generated {len(written)} files\n")
        return 0
    problems = check(args.root)
    for problem in problems:
        sys.stderr.write(problem + "\n")
    sys.stdout.write(f"feature schema: {'fail' if problems else 'pass'}\n")
    return int(bool(problems))


