"""Schema of the wide feature tables, and the files generated from it.

Run from the repository root:

    .venv/bin/python -m scripts.features.feature_schema generate
    .venv/bin/python -m scripts.features.feature_schema check

``generate`` writes four kinds of committed file from one computation: ``data_contracts/features/feature_schema.json`` (per table the ordered columns with
SQL type, Feast type, role, registered view, pivot mapping and mask rule, and the list of online-servable features), one dbt model per table in
``dbt/models/features/matrix/``, ``dbt/models/features/matrix/_feature_matrix__models.yml`` (types and descriptions, the enforced contract that
``scripts/lakehouse/feature_columns.py`` checks) and ``feature_store/definitions.py`` (the Feast repository). ``check`` regenerates them in memory and
fails on any byte difference, on a ``feature_matrix_*`` or ``label_matrix_*`` model without a schema entry and on a generated file that is missing.

The column list is fixed by the registry, never by a run's data. The controls come from the frozen identity seeds in ``dbt/seeds/features`` (the
``assert_*_control_identity`` tests hold them equal to the models); the fields a model writes in SQL and the kind of a key that is not a number come from
the reviewed ``data_contracts/features/feature_schema_rules.json``. The generator fails, before it writes anything, on two keys that fold to one column
name, on a name over 128 characters, on a rule that names no key and on a control that is excluded from predictors. It reads no dbt and no Feast.
"""

