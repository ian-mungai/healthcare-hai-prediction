def read_json(path: Path) -> Any:
    """A JSON file."""
    return json.loads(path.read_text())


def read_seed(root: Path, name: str) -> list[dict[str, str]]:
    """The rows of a feature seed CSV."""
    with (root / SEEDS / f"{name}.csv").open(newline="") as handle:
        return list(csv.DictReader(handle))


def sanitize(text: str) -> str:
    """Lower case, every character outside a-z and 0-9 as an underscore."""
    return re.sub(r"[^a-z0-9]", "_", text.lower())


def column_name(control: str, field: str, kind: str) -> str:
    """The wide column of a key: ``<control>__<field>__<kind>``."""
    return f"{sanitize(control)}__{sanitize(field)}__{kind}"


def care_compare_keys(root: Path, rules: dict[str, Any]) -> set[Key]:
    """One key per control; the family has no field and no source column."""
    return {("", row["measure_control"], "value") for row in read_seed(root, "frozen_care_compare_controls")}


def hospital_keys(root: Path, rules: dict[str, Any]) -> set[Key]:
    """The source, control and field rows of the cost report, impact, Medicare inpatient and occupational mix families."""
    return {(row["measure_source"], row["measure_control"], row["field"]) for row in read_seed(root, "frozen_hospital_controls")}


def operations_keys(root: Path, rules: dict[str, Any]) -> set[Key]:
    """The carried controls of HHS capacity, ONC and ownership; the family has no field."""
    return {(row["measure_source"], row["measure_control"], "value") for row in read_seed(root, "frozen_operations_controls") if row["is_carried"] == "true"}


def county_measures_keys(root: Path, rules: dict[str, Any]) -> set[Key]:
    """PLACES, geographic variation, WONDER, MMD and RUCC keys, as the county measures model writes them."""
    value_types = rules["source_fields"]["places_value_types"]
    keys: set[Key] = set()
    for row in read_seed(root, "frozen_county_controls"):
        control, fact, measure = row["measure_control"], row["fact"], row["measure_key"]
        if row["retired_seed"] == "county_health_measures":
            if fact == "fct_places_county_value":
                keys.update(("places", control, f"{measure}:{value_type}") for value_type in value_types)
            elif fact == "fct_gv_county_value":
                keys.add(("geographic_variation", control, measure))
            elif fact == "fct_wonder_county_deaths":
                keys.add(("wonder", control, measure))
        elif row["retired_seed"] == "mmd_conditions" and row["geography_level"] == "county":
            keys.add(("mmd", control, "prevalence"))
        elif row["retired_seed"] == "geography_measures" and fact == "fct_rucc_county":
            keys.add(("rucc", control, "rucc_code"))
    return keys


def county_context_keys(root: Path, rules: dict[str, Any]) -> set[Key]:
    """ACS, SVI, SAIPE, SAHIE, BLS, HPSA, MUA and RUCA keys, as the county context model writes them."""
    fields = rules["source_fields"]
    identity = set(fields["income_labor_identity_keys"])
    sources = {"fct_acs_county_value": "acs", "fct_svi_county_value": "svi", "fct_saipe_county_estimate": "saipe", "fct_sahie_county_value": "sahie"}
    keys: set[Key] = set()
    for row in read_seed(root, "frozen_county_controls"):
        control, fact, measure = row["measure_control"], row["fact"], row["measure_key"]
        if row["retired_seed"] == "acs_svi_measures":
            keys.add((sources[fact], control, measure))
        elif row["retired_seed"] == "income_labor_measures" and measure not in identity:
            keys.add((sources.get(fact, "bls"), control, measure))
        elif row["retired_seed"] == "shortage_measures":
            designated = fields["designation_fields"]
            source = "hpsa" if fact == "fct_hpsa_component" else "mua"
            keys.update((source, control, field) for field in designated.get(control, designated["default"]))
        elif row["retired_seed"] == "geography_measures" and fact == "fct_ruca_code" and measure in fields["ruca_fields"]:
            keys.add(("ruca", control, measure))
    return keys


