"""The files that can change what the launcher E2E suite runs: the list that selects the ``launcher`` group of config/quality/ci_groups.json.

The list is computed, not written: from the entry points in config/quality/launcher_inputs.json it follows every module a Python file imports (also inside
functions and in code held in strings), every module a string, an f-string or a text file names (``python -m x.y``), every tracked file a string, a ``/`` join
or an f-string names (scripts/quality/source_reads.py; a folder that a module names selects every file under it, because the module may hash or copy the whole
folder) and the same for each file found, until nothing new appears. A file that only a whole-folder read or ``extra_inputs`` names is listed but not followed.
``extra_inputs`` names files or folders the suite needs that no string names. ``ignored_reads`` names a (module, text) pair that the scan reads as a path but
the suite does not read (a mount source compared as a string, a terraform ``-chdir`` argument); each has its reason and fails the check when it no longer
matches. Parent packages come with each module. Calls that import or open a module by a computed name (``importlib.import_module(name)``) cannot be followed:
they are counted per file in ``dynamic_sites`` of the committed list, so a new one changes the computed list.

    .venv/bin/python -m scripts.quality.launcher_inputs --check          # the committed list equals the computed list (the default)
    .venv/bin/python -m scripts.quality.launcher_inputs --write          # recompute and write the committed list
    .venv/bin/python -m scripts.quality.launcher_inputs --explain PATH   # why a file is in the list
    .venv/bin/python -m scripts.quality.launcher_inputs --trace FILE     # tracked files opened in a traced run (one path per line) that the list misses

scripts/quality/ci_groups.py adds one exact-path pattern per listed file to the ``launcher`` group. E2E: scripts/quality/run_ci_groups_e2e.py.
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from pathlib import Path
from typing import Any

from scripts.process import run_command
from scripts.quality.source_reads import fills_template, source_inputs

LIST = Path("config/quality/launcher_inputs.json")
BODY = "scripts/ci/groups/launcher.sh"
TEXT_SUFFIXES = {".sh", ".yaml", ".yml", ".tmpl", ".toml"}
DOTTED = re.compile(r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)+")
SLASHED = re.compile(r"[\w.\-]+(?:/[\w.\-]+)+")
IMPORT_LINE = re.compile(r"^[ \t]*(?:from[ \t]+([\w.]+)[ \t]+import[ \t]+([\w, ]+)|import[ \t]+([\w., ]+))", re.MULTILINE)
DYNAMIC_IMPORTS = {"import_module": 0, "__import__": 0, "spec_from_file_location": 1}
NOTE = (
    "Generated by scripts/quality/launcher_inputs.py --write: the files that can change what the launcher E2E suite "
    "(scripts/lakehouse/run_launcher_e2e.py, started by scripts/ci/groups/launcher.sh) runs, selected by scripts/quality/ci_groups.py for the launcher "
    "group. entry_points and extra_inputs are the only hand-written keys; files and dynamic_sites are computed and --check fails when they differ."
)


def module_files(name: str, tracked: set[str]) -> set[str]:
    """The tracked files that importing module ``name`` runs: the module and the ``__init__.py`` of each parent package."""
    parts = name.split(".")
    found = set()
    for end in range(1, len(parts) + 1):
        base = "/".join(parts[:end])
        found |= {candidate for candidate in (f"{base}.py", f"{base}/__init__.py") if candidate in tracked}
    return found


def imported_modules(tree: ast.AST, path: str) -> set[str]:
    """Every module name an import statement of the file names, also inside functions; a relative import resolves against the file's package."""
    names: set[str] = set()
    package = list(Path(path).parent.parts)
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            base = package[: len(package) - (node.level - 1)] if node.level else []
            module = ".".join([*base, *([node.module] if node.module else [])])
            names.add(module)
            names.update(f"{module}.{alias.name}" for alias in node.names)
    return {name for name in names if name}


def embedded_modules(text: str) -> set[str]:
    """Modules that a string holding Python code imports (``from x import y`` and ``import x`` lines)."""
    names: set[str] = set()
    for source, imported, plain in IMPORT_LINE.findall(text):
        if source:
            names.add(source)
            names.update(f"{source}.{item.strip()}" for item in imported.split(","))
        else:
            names.update(item.strip().split(" ")[0] for item in plain.split(","))
    return names


def dynamic_sites(tree: ast.AST) -> int:
    """The calls that import or load a module by a name or path that is not a string literal."""
    count = 0
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        name = node.func.attr if isinstance(node.func, ast.Attribute) else node.func.id if isinstance(node.func, ast.Name) else ""
        position = DYNAMIC_IMPORTS.get(name)
        if position is None:
            continue
        argument = node.args[position] if len(node.args) > position else None
        if not (isinstance(argument, ast.Constant) and isinstance(argument.value, str)):
            count += 1
    return count


def python_inputs(text: str, path: str, tracked: set[str], ignored: set[str]) -> tuple[dict[str, tuple[str, bool]], int, set[str], set[str]]:
    """The tracked files a Python file needs, each with the reason and whether the suite may run or read its contents (False for a file that only a whole-folder
    read names: it is in the list but its own imports and reads are not followed), its number of dynamic import calls and the texts of ``ignored`` that
    it names (a reviewed read that the suite does not make: those files are not taken from that text) and the folders it reads whole."""
    tree = ast.parse(text)
    found: dict[str, tuple[str, bool]] = {}
    for name in imported_modules(tree, path):
        for item in module_files(name, tracked):
            found.setdefault(item, (f"imports {name}", True))
    docstrings = {id(node.value) for node in ast.walk(tree) if isinstance(node, ast.Expr)}
    in_fstring = {id(part) for node in ast.walk(tree) if isinstance(node, ast.JoinedStr) for part in node.values}
    strings = {
        node.value
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant) and isinstance(node.value, str) and id(node) not in in_fstring and id(node) not in docstrings
    }
    for value in strings:
        for name in [*DOTTED.findall(value), *embedded_modules(value)]:
            for item in module_files(name, tracked):
                found.setdefault(item, (f"names module {name}", True))
    modules = sorted(item[:-3].replace("/", ".") for item in tracked if item.endswith(".py") and not item.endswith("__init__.py"))
    for node in ast.walk(tree):
        if isinstance(node, ast.JoinedStr):
            template = [part.value if isinstance(part, ast.Constant) and isinstance(part.value, str) else None for part in node.values]
            if None in template and template[0] and "." in template[0]:
                for name in modules:
                    if fills_template(template, name, strings):
                        found.setdefault(f"{name.replace('.', '/')}.py", (f"f-string names module {name}", True))
    skipped: set[str] = set()
    folders: set[str] = set()
    for item, reason in source_inputs(text, tracked, rooted=True).items():
        whole_file = reason.strip("/") == item or reason.startswith('f"')
        if reason in ignored:
            skipped.add(reason)
        else:
            found.setdefault(item, (f"reads {reason}", whole_file))
            if not whole_file:
                folders.add(reason.strip("/"))
    return found, dynamic_sites(tree), skipped, folders


def text_inputs(text: str, tracked: set[str]) -> dict[str, str]:
    """The tracked files a shell, YAML or template file names: dotted module names and exact paths. A folder it names (a volume mount, a build context) is not
    read: the suite starts no container, so the files in it run only when a module name or a path reaches them."""
    found: dict[str, str] = {}
    for name in DOTTED.findall(text):
        for item in module_files(name, tracked):
            found.setdefault(item, f"names module {name}")
    for token in SLASHED.findall(text):
        token = token.removeprefix("./").strip("/")
        if token in tracked:
            found.setdefault(token, f"names {token}")
    return found


def compute(
    root: Path, tracked: set[str], entry_points: list[str], extra_inputs: list[str], ignored_reads: list[dict[str, str]] | None = None
) -> dict[str, Any]:
    """The sorted files, why each is in, the dynamic import calls per file and the ``ignored_reads`` that matched; follows imports and reads from the entry
    points until nothing is new. A file reached only through a whole-folder read or ``extra_inputs`` is in the list but not followed (it is data, not run)."""
    ignored = [(item["module"], item["text"]) for item in ignored_reads or []]
    matched: set[tuple[str, str]] = set()
    folders: set[str] = set()
    why: dict[str, str] = {}
    queue: list[str] = []
    sites: dict[str, int] = {}

    follow: dict[str, bool] = {}

    def add(path: str, reason: str, runs: bool = True) -> None:
        if path not in tracked or (path in why and (follow[path] or not runs)):
            return
        why.setdefault(path, reason)
        follow[path] = runs
        queue.append(path)

    for path in entry_points:
        add(path, "entry point")
        for item in module_files(path.removesuffix(".py").replace("/", "."), tracked):
            add(item, f"package of {path}")
    for path in extra_inputs:
        whole_folder = path not in tracked
        if whole_folder:
            folders.add(path)
        for item in [path] if not whole_folder else sorted(item for item in tracked if item.startswith(f"{path}/")):
            add(item, f"extra input {path}", runs=False)
    while queue:
        path = queue.pop()
        suffix = Path(path).suffix
        if not follow[path]:
            continue
        if suffix == ".py":
            found, count, skipped, read_whole = python_inputs(
                (root / path).read_text(encoding="utf-8"), path, tracked, {text for module, text in ignored if module == path}
            )
            matched |= {(path, text) for text in skipped}
            folders |= read_whole
            if count:
                sites[path] = count
        elif suffix in TEXT_SUFFIXES:
            found = {item: (reason, True) for item, reason in text_inputs((root / path).read_text(encoding="utf-8", errors="replace"), tracked).items()}
        else:
            continue
        for item, (reason, runs) in found.items():
            add(item, f"{reason} in {path}", runs)
    return {
        "files": sorted(why),
        "dynamic_sites": dict(sorted(sites.items())),
        "why": why,
        "followed": sorted(path for path in why if follow[path]),
        "ignored": matched,
        "folders": sorted(folders),
    }


def listing(root: Path, tracked: set[str], committed: dict[str, Any]) -> dict[str, Any]:
    computed = compute(root, tracked, committed["entry_points"], committed["extra_inputs"], committed.get("ignored_reads"))
    return {
        "note": NOTE,
        "entry_points": committed["entry_points"],
        "extra_inputs": committed["extra_inputs"],
        "ignored_reads": committed.get("ignored_reads", []),
        "dynamic_sites": computed["dynamic_sites"],
        "folders": computed["folders"],
        "files": computed["files"],
    }


def problems(root: Path, tracked: set[str], committed: dict[str, Any]) -> list[str]:
    """Why the committed list is not the computed list: each line names the file."""
    computed = compute(root, tracked, committed["entry_points"], committed["extra_inputs"], committed.get("ignored_reads"))
    wanted, held = set(computed["files"]), set(committed["files"])
    lines = [f"{path}: the launcher suite needs it ({computed['why'][path]}) but the list lacks it" for path in sorted(wanted - held)]
    lines += [
        f"{folder}/: the suite reads the folder whole but folders lacks it" for folder in sorted(set(computed["folders"]) - set(committed.get("folders", [])))
    ]
    lines += [
        f"{folder}/: in folders but the suite no longer reads it whole" for folder in sorted(set(committed.get("folders", [])) - set(computed["folders"]))
    ]
    lines += [f"{path}: in the list but the suite no longer needs it" for path in sorted(held - wanted) if path in tracked]
    lines += [f"{path}: in the list but not tracked (deleted or renamed)" for path in sorted(held - tracked)]
    lines += [
        f"{item['module']}: ignored read {item['text']!r} is no longer in the module (remove it from ignored_reads)"
        for item in committed.get("ignored_reads", [])
        if (item["module"], item["text"]) not in computed["ignored"]
    ]
    for path in sorted(set(computed["dynamic_sites"]) | set(committed["dynamic_sites"])):
        if computed["dynamic_sites"].get(path, 0) != committed["dynamic_sites"].get(path, 0):
            now, before = computed["dynamic_sites"].get(path, 0), committed["dynamic_sites"].get(path, 0)
            lines.append(f"{path}: {now} calls import by a computed name, the list records {before}; review and run --write")
    body = root / BODY
    modules = re.findall(r"-m ([\w.]+)", body.read_text(encoding="utf-8")) if body.exists() else []
    entries = {path.removesuffix(".py").replace("/", ".") for path in committed["entry_points"]}
    if not modules or set(modules) - entries:
        lines.append(f"{BODY}: starts {modules or 'no module'} but the entry points are {sorted(entries)}")
    return lines


def selection_gaps(config: dict[str, Any], files: list[str], tracked: set[str]) -> list[str]:
    """Listed files that the ``launcher`` patterns (after ci_groups.load) and ``global`` do not select, and patterns that match no tracked file."""
    selecting = [*config["groups"]["launcher"], *config["global"]]
    gaps = [
        f"{path}: listed, but neither the launcher patterns nor global select it"
        for path in files
        if not any(re.search(pattern, path) for pattern in selecting)
    ]
    gaps += [
        f"{pattern}: a launcher pattern that matches no tracked file"
        for pattern in config["groups"]["launcher"]
        if not any(re.search(pattern, path) for path in tracked)
    ]
    return gaps


def trace_gaps(opened: list[str], tracked: set[str], files: list[str]) -> list[str]:
    """Tracked files opened in a traced run that the list does not hold."""
    return [path for path in sorted({item.removeprefix("./") for item in opened}) if path in tracked and path not in set(files)]


def tracked_files(root: Path) -> set[str]:
    result = run_command("git", ["-C", str(root), "ls-files", "--cached"], timeout=120, check=True)
    return {line for line in result.stdout.splitlines() if line}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--check", action="store_true", help="fail when the committed list differs from the computed list (default)")
    action.add_argument("--write", action="store_true", help="write the computed list")
    action.add_argument("--explain", metavar="PATH", help="print why a file is in the list")
    action.add_argument("--trace", metavar="FILE", type=Path, help="fail for tracked files opened in a traced run that the list misses")
    args = parser.parse_args(argv)
    root = Path.cwd()
    tracked = tracked_files(root)
    committed = json.loads((root / LIST).read_text(encoding="utf-8"))
    if args.write:
        (root / LIST).write_text(json.dumps(listing(root, tracked, committed), indent=2) + "\n", encoding="utf-8")
        return 0
    if args.explain:
        reason = compute(root, tracked, committed["entry_points"], committed["extra_inputs"], committed.get("ignored_reads"))["why"].get(args.explain)
        sys.stdout.write(f"{args.explain}: {reason or 'not in the list'}\n")
        return 0 if reason else 1
    if args.trace:
        opened = [
            str(Path(line.strip()).relative_to(root)) if line.strip().startswith(str(root)) else line.strip()
            for line in args.trace.read_text().splitlines()
            if line.strip()
        ]
        missed = trace_gaps(opened, tracked, committed["files"])
        for path in missed:
            sys.stderr.write(f"{path}: opened by the traced launcher run but not in {LIST}\n")
        return 1 if missed else 0
    found = problems(root, tracked, committed)
    for line in found:
        sys.stderr.write(f"{LIST}: {line}\n")
    if found:
        sys.stderr.write("Run: .venv/bin/python -m scripts.quality.launcher_inputs --write (then review the diff)\n")
    return 1 if found else 0


if __name__ == "__main__":
    raise SystemExit(main())
