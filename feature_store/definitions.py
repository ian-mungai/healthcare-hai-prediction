def setting(name: str) -> str:
    """A required environment variable; the job refuses to load the repository without it."""
    value = os.environ.get(name, "")
    if not value or "${" in value:
        raise RuntimeError(f"{name} is not set")
    return value


def iceberg_source(table: str) -> IcebergSource:
    """The offline source of one table of the closed namespace and catalog type."""
    namespace = setting("FEAST_NAMESPACE")
    catalog_type = setting("FEAST_CATALOG_TYPE")
    if namespace not in NAMESPACES or catalog_type not in CATALOG_TYPES:
        raise RuntimeError("FEAST_NAMESPACE or FEAST_CATALOG_TYPE has a value outside its closed list")
    if catalog_type == "rest":
        return IcebergSource(
            name=table,
            catalog_type="rest",
            catalog_name=CATALOG_NAME,
            endpoint=setting("FEAST_CATALOG_ENDPOINT"),
            warehouse=WAREHOUSE,
            namespace=namespace,
            table=table,
            token_env_var=CREDENTIAL_VARIABLE,
            credential_vending=False,
            timestamp_field=EVENT_TIME,
        )
    uri = setting("FEAST_SQL_CATALOG_URI")
    folder = setting("FEAST_RUN_FOLDER").rstrip("/")
    if namespace != "features_e2e" or not uri.startswith(f"sqlite:///{folder}/"):
        raise RuntimeError("the sql catalog is allowed only for features_e2e with a SQLite file in the run folder")
    return IcebergSource(
        name=table,
        catalog_type="sql",
        catalog_name=CATALOG_NAME,
        warehouse=WAREHOUSE,
        namespace=namespace,
        table=table,
        catalog_properties={"uri": uri, "warehouse": setting("FEAST_SQL_WAREHOUSE")},
        credential_vending=False,
        timestamp_field=EVENT_TIME,
    )


