def view(name: str, online: bool) -> FeatureView:
    """One feature view over one table: ttl 0 (no lower bound for the point-in-time join), types Float64, Int64, String and Bool only."""
    table, fields = (name, PREDICTOR_VIEWS[name]) if online else LABEL_VIEWS[name]
